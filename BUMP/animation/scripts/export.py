"""Reads the actions BUMP plays from BUMP_Animations.blend and writes them as Luau.

    /Applications/Blender.app/Contents/MacOS/Blender -b animation/BUMP_Animations.blend -P animation/scripts/export.py

Only the clips in clips_bump.exported_names() are written: the file holds The Scramble's whole
library, most of which BUMP has no use for.

Every action is sampled at 30 fps from the evaluated pose, so constraints and hand edits are
included exactly as they look in Blender. Each joint then keeps only the frames it needs to stay
within TOLERANCE of that, which is what keeps the data small enough to send to every client.
"""

import json
import math
import os
import sys

import bpy

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import clips_bump  # noqa: E402
import fias_pose  # noqa: E402
import fias_rig  # noqa: E402

ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
OUT_DIR = os.path.join(ROOT, "src", "Shared", "Movement", "AnimationData")
TOLERANCE_DEGREES = 0.7
TOLERANCE_STUDS = 0.012
TRACK_SUFFIX = {"_A": "Attacker", "_V": "Victim"}
CORE_HEADER = "--!nonstrict\n-- Generated by animation/scripts/export.py from BUMP_Animations.blend. Do not edit.\n"


def angle_between(a, b):
    dot = abs(sum(x * y for x, y in zip(a, b)))
    return 2 * math.acos(min(dot, 1))


def nlerp(a, b, t):
    q = [x + (y - x) * t for x, y in zip(a, b)]
    length = math.sqrt(sum(v * v for v in q)) or 1
    return [v / length for v in q]


def thin(rotations, positions):
    """Frame indices to keep. Greedy split on the worst error, like Douglas-Peucker."""
    tolerance = math.radians(TOLERANCE_DEGREES)
    keep = {0, len(rotations) - 1}

    def split(first, last):
        worst, worst_error = None, 0
        for i in range(first + 1, last):
            t = (i - first) / (last - first)
            error = angle_between(nlerp(rotations[first], rotations[last], t), rotations[i]) / tolerance
            if positions is not None:
                blend = [x + (y - x) * t for x, y in zip(positions[first], positions[last])]
                error = max(error, max(abs(x - y) for x, y in zip(blend, positions[i])) / TOLERANCE_STUDS)
            if error > worst_error:
                worst, worst_error = i, error
        if worst is not None and worst_error > 1:
            keep.add(worst)
            split(first, worst)
            split(worst, last)

    split(0, len(rotations) - 1)
    return sorted(keep)


def named_joints(action, armature):
    bag = fias_pose.channelbag(action, armature)
    joints = set()
    for curve in bag.fcurves:
        if curve.data_path.startswith('pose.bones["'):
            name = curve.data_path.split('"')[1]
            if name in fias_pose.ALL_JOINTS and "constraints" not in curve.data_path:
                joints.add(name)
    if action.get("two_hand"):
        joints.update(("LS", "LE"))
    return joints


def sample(action, armature):
    scene = bpy.context.scene
    # Older actions don't key the far hold, so it must not be left on from the last one sampled.
    far = armature.pose.bones["LE"].constraints.get("LeftHandFar")
    if far is not None:
        far.influence = 0.0
    armature.animation_data.action = action
    if armature.animation_data.action_suitable_slots:
        armature.animation_data.action_slot = armature.animation_data.action_suitable_slots[0]
    first, last = (int(round(v)) for v in action.frame_range)
    joints = sorted(named_joints(action, armature))
    rotations = {joint: [] for joint in joints}
    positions = []
    for frame in range(first, last + 1):
        scene.frame_set(frame)
        bpy.context.view_layer.update()
        for joint in joints:
            rotation, moved = fias_rig.pose_to_delta(armature, armature.pose.bones[joint])
            q = list(fias_rig.quaternion_r(rotation))
            previous = rotations[joint][-1] if rotations[joint] else None
            if previous and sum(x * y for x, y in zip(previous, q)) < 0:
                q = [-v for v in q]
            rotations[joint].append(q)
            if joint == "Root":
                positions.append(list(moved))
    tracks = {}
    for joint in joints:
        moves = positions if joint == "Root" else None
        kept = thin(rotations[joint], moves)
        track = {"T": [round(i / fias_pose.FPS, 4) for i in kept], "Q": [round(v, 4) for i in kept for v in rotations[joint][i]]}
        if moves is not None and any(abs(v) > 0.001 for p in moves for v in p):
            track["P"] = [round(v, 3) for i in kept for v in moves[i]]
        tracks[joint] = track
    return {
        "Seconds": round((last - first) / fias_pose.FPS, 4),
        "Loop": bool(action.get("loop")),
        "Markers": {m.name: round((m.frame - first) / fias_pose.FPS, 4) for m in action.pose_markers},
        "Joints": tracks,
    }


def sample_camera(action, camera):
    scene = bpy.context.scene
    camera.animation_data.action = action
    if camera.animation_data.action_suitable_slots:
        camera.animation_data.action_slot = camera.animation_data.action_suitable_slots[0]
    first, last = (int(round(v)) for v in action.frame_range)
    frames = []
    for frame in range(first, last + 1):
        scene.frame_set(frame)
        bpy.context.view_layer.update()
        world = camera.matrix_world
        # Blender and Roblox cameras both look down their own -Z with +Y up, so only the world differs.
        location = fias_rig.b2r(world.to_translation())
        rotation = fias_rig.C_INV @ world.to_3x3()
        frames.append((location, rotation, float(camera["fov"])))
    step = 2
    samples = frames[::step]
    if (len(frames) - 1) % step:
        samples.append(frames[-1])
    out = {"Step": step / fias_pose.FPS, "P": [], "Q": [], "Fov": []}
    for location, rotation, fov in samples:
        out["P"] += [round(v, 2) for v in location]
        out["Q"] += [round(v, 4) for v in fias_rig.quaternion_r(rotation)]
        out["Fov"].append(round(fov, 1))
    return out


def luau(value, indent=0):
    if isinstance(value, dict):
        if not value:
            return "{}"
        pad = "\t" * (indent + 1)
        lines = []
        for key in sorted(value):
            name = key if key.isidentifier() else json.dumps(key)
            if not key.isidentifier():
                name = f"[{name}]"
            lines.append(f"{pad}{name} = {luau(value[key], indent + 1)},")
        return "{\n" + "\n".join(lines) + "\n" + "\t" * indent + "}"
    if isinstance(value, (list, tuple)):
        return "{ " + ", ".join(luau(v, indent) for v in value) + " }" if value else "{}"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, float):
        return repr(round(value, 4)).rstrip("0").rstrip(".") if "e" not in repr(value) else "0"
    if isinstance(value, str):
        return json.dumps(value)
    return str(value)


def write(name, data):
    os.makedirs(OUT_DIR, exist_ok=True)
    path = os.path.join(OUT_DIR, name + ".lua")
    text = CORE_HEADER + "return " + luau(data) + "\n"
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"[Export] {name}: {len(data)} clips, {len(text) // 1024} KB")


def main():
    fighter = bpy.data.objects["Fighter"]
    core = {}
    wanted = clips_bump.exported_names()
    for action in sorted(bpy.data.actions, key=lambda a: a.name):
        name = action.name
        if name not in wanted:
            continue
        fighter.animation_data_create()
        fighter.animation_data.action = action
        core[name] = sample(action, fighter)
    missing = wanted - set(core)
    if missing:
        raise SystemExit(f"[Export] missing actions: {sorted(missing)}")
    write("Core", core)


main()
